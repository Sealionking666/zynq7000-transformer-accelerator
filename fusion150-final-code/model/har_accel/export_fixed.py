"""Generate C constants and full-propagation model GEMM vectors, INT8 nearest."""
import json
import hashlib
from pathlib import Path
import numpy as np
import torch
from .data import ROOT, load_train_val, sha256
from .fixed_network import LINEARS, INPUTS, compile_parameters, input_to_q16, forward_q16


def c_array(name, values, dtype):
    a = np.asarray(values).ravel()
    rows = [", ".join(str(int(v)) for v in a[i:i+16]) for i in range(0,len(a),16)]
    return f"static const {dtype} {name}[{len(a)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main():
    state = torch.load(ROOT / "artifacts/float_model/weights.pt",map_location="cpu",weights_only=True)
    cand = json.loads((ROOT / "artifacts/quant_candidate.json").read_text())
    p = compile_parameters(state,cand,8,"nearest")
    out = ROOT / "FPGA/runtime/generated"
    out.mkdir(parents=True,exist_ok=True)
    header = "// Generated by python -m har_accel.export_fixed. Do not edit.\n#pragma once\n#include <stdint.h>\n"
    header += f"#define HAR_EPSILON_Q32 {p['epsilon_q32']}\n"
    for name in LINEARS:
        header += f"#define HAR_{name}_INPUT_EXP {p['activation_exp'][INPUTS[name]]}\n#define HAR_{name}_WEIGHT_EXP {p['weight_exp'][name]}\n"
        header += c_array('har_'+name+'_weight',p[name+'_weight'],'int8_t')
        header += c_array('har_'+name+'_bias',p[name+'_bias'],'int32_t')
    for macro,key in [('Q','q'),('K','k'),('V','v'),('PROB','softmax_prob')]:
        header += f"#define HAR_{macro}_EXP {p['activation_exp'][key]}\n"
    for name in ['position','norm1_gamma','norm2_gamma','exp_lut']:
        header += c_array('har_'+name,p[name],'int32_t')
    (out/'har_parameters.h').write_text(header,encoding='utf-8')
    _,_,x,y=load_train_val()
    _,trace,_=forward_q16(input_to_q16(x[:1]),p,capture=True)
    vectors=[]
    for name in ['embed','q','k','v','qk_scores','av','out','ff1','ff2','classifier']:
        a,b,acc=trace[name+'.a'],trace[name+'.b'],trace[name+'.acc']
        if a.ndim==3:a=a[0]
        if b.ndim==3:b=b[0]
        if acc.ndim==3:acc=acc[0]
        # Independent scalar recomputation prevents trusting only numpy matmul.
        expected=[[sum(int(a[i,t])*int(b[t,j]) for t in range(b.shape[0])) for j in range(b.shape[1])] for i in range(a.shape[0])]
        if not np.array_equal(acc,np.array(expected)):raise AssertionError(name)
        vectors.append({'name':name,'m':a.shape[0],'k':a.shape[1],'n':b.shape[1],'a':a.tolist(),'b':b.tolist(),'expected_raw32':expected})
    (out/'model_vectors.json').write_text(json.dumps({'scope':'full integer propagation, validation sample 0, INT8 nearest contract','vectors':vectors},separators=(',',':'))+'\n')
    vh='// Full integer propagation model vectors; separate from engine stress vectors.\n#pragma once\n#include <stdint.h>\n'
    vh+='struct HarModelVector { const char *name; int m,k,n; int8_t a[1152],b[1152]; int32_t expected[1024]; };\nstatic const HarModelVector har_model_vectors[] = {\n'
    for v in vectors:
        fmt=lambda a:','.join(str(int(z)) for row in a for z in row)
        vh+='{"'+v['name']+'",'+','.join(str(v[k]) for k in ['m','k','n'])+', {'+fmt(v['a'])+'}, {'+fmt(v['b'])+'}, {'+fmt(v['expected_raw32'])+'}},\n'
    vh+='};\n#define HAR_MODEL_VECTOR_COUNT 10\n'
    (out/'model_vectors.h').write_text(vh,encoding='utf-8')
    demo_indices=np.array([int(np.flatnonzero(y == label)[0]) for label in range(6)])
    logits,_,_=forward_q16(input_to_q16(x[demo_indices]),p)
    demo='// One validation input per class; repeated-call checks, not accuracy estimation.\n#pragma once\n#include <stdint.h>\n#define HAR_DEMO_COUNT 6\n'
    demo+=c_array('har_demo_indices',demo_indices,'int32_t')
    demo+=c_array('har_demo_inputs',input_to_q16(x[demo_indices]),'int32_t')
    demo+=c_array('har_demo_logits',logits,'int32_t')
    demo+=c_array('har_demo_labels',y[demo_indices],'int32_t')
    (out/'har_demo.h').write_text(demo,encoding='utf-8')
    manifest={'weights_sha256':sha256(ROOT/'artifacts/float_model/weights.pt'),'contract':'INT8 GEMM / INT32 raw32 / Q16 PS / nearest activation quantization / floor scale reduction',
              'model_vectors':len(vectors),'files':{f.name:sha256(f) for f in out.iterdir() if f.is_file() and f.name!='manifest.json'}}
    (out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest,indent=2))


if __name__=='__main__':main()
